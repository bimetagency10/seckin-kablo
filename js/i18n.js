(function(){
  'use strict';
  var REAL = ['tr','en'];
  var AUTO = ['de','ar','ru'];          /* Google Translate */
  var RTL  = ['ar'];
  var CODE = {tr:'TR',en:'EN',de:'DE',ar:'AR',ru:'RU'};
  var NAMES = {tr:'Türkçe',en:'English',de:'Deutsch',ar:'العربية',ru:'Русский'};
  var reduce = window.matchMedia && window.matchMedia('(prefers-reduced-motion: reduce)').matches;

  function isAuto(l){ return AUTO.indexOf(l) !== -1; }
  function getLang(){
    var l = new URLSearchParams(location.search).get('lang');
    return (l && (REAL.indexOf(l)!==-1 || isAuto(l))) ? l : 'tr';
  }
  function dictFor(lang){
    /* real langs use their dict; auto langs render from Turkish base then GT translates */
    var base = (lang === 'en') ? window.I18N.en : window.I18N.tr;
    return base || {};
  }

  function applyDict(lang){
    var d = dictFor(lang), tr = window.I18N.tr;
    document.documentElement.lang = lang;
    document.documentElement.dir = RTL.indexOf(lang)!==-1 ? 'rtl' : 'ltr';
    var i, els, v;
    els = document.querySelectorAll('[data-i18n]');
    for (i=0;i<els.length;i++){
      v = els[i].getAttribute('data-i18n');
      var val = (d[v]!=null) ? d[v] : tr[v];
      if (val!=null) els[i].textContent = val;
    }
    els = document.querySelectorAll('[data-i18n-html]');
    for (i=0;i<els.length;i++){
      v = els[i].getAttribute('data-i18n-html');
      var vh = (d[v]!=null) ? d[v] : tr[v];
      if (vh!=null) els[i].innerHTML = vh;
    }
  }

  /* ---- Google Translate cookie helpers ---- */
  function setCookie(v){ document.cookie = 'googtrans=' + v + ';path=/'; }
  function clearGT(){
    var kill = 'googtrans=;expires=Thu, 01 Jan 1970 00:00:00 GMT;path=/';
    document.cookie = kill;
    try { document.cookie = kill + ';domain=' + location.hostname; } catch(e){}
    try { document.cookie = kill + ';domain=.' + location.hostname; } catch(e){}
  }
  var gtLoaded = false;
  function skConsentOk(){
    try { return window.SK_consent ? window.SK_consent.ok() : (localStorage.getItem('sk-cerez-tercihi') === 'tum'); }
    catch(e){ return false; }
  }
  function ensureGT(){
    if (!skConsentOk()) return; /* cerez onayi olmadan Google Translate yuklenmez (KVKK) */
    if (gtLoaded) return; gtLoaded = true;
    if (!document.getElementById('google_translate_element')){
      var d = document.createElement('div');
      d.id = 'google_translate_element'; d.setAttribute('aria-hidden','true');
      document.body.appendChild(d);
    }
    window.googleTranslateElementInit = function(){
      /* eslint-disable no-undef */
      new google.translate.TranslateElement(
        { pageLanguage:'tr', includedLanguages:'en,de,ru,ar', autoDisplay:false },
        'google_translate_element');
    };
    var s = document.createElement('script'); s.async = true;
    s.src = 'https://translate.google.com/translate_a/element.js?cb=googleTranslateElementInit';
    document.body.appendChild(s);
  }

  function gotoLang(l){ var u = new URL(location.href); u.searchParams.set('lang', l); location.assign(u.href); }
  function pushLang(l){ var u = new URL(location.href); u.searchParams.set('lang', l); history.replaceState(null,'',u.href); }

  function setLang(target){
    var cur = getLang();
    if (target === cur){ closeAll(); return; }
    if (isAuto(target)){
      if (!skConsentOk()){
        if (window.SK_consent) window.SK_consent.request(function(){ setCookie('/tr/' + target); gotoLang(target); });
        closeAll(); return;
      }
      setCookie('/tr/' + target); gotoLang(target); return;
    }
    /* target is a real language (tr/en) */
    clearGT();
    if (isAuto(cur)){ gotoLang(target); return; }   /* shed GT-mutated DOM via reload */
    applyDict(target); pushLang(target); syncSwitchers(target); closeAll();
  }
  window.SK_setLang = setLang;

  /* ---- Switcher UI ---- */
  function optionList(active){
    return ['tr','en','de','ar','ru'].map(function(l){
      var on = l===active ? ' aria-selected="true" class="on"' : ' aria-selected="false"';
      return '<li role="none"><button type="button" role="option" data-lang="'+l+'"'+on+
             (l==='ar'?' dir="rtl"':'')+'>'+NAMES[l]+'</button></li>';
    }).join('');
  }
  function buildDesktop(active){
    var wrap = document.querySelector('.nav-cta'); if (!wrap) return;
    if (wrap.querySelector('.lang-switch')) return;
    var box = document.createElement('div');
    box.className = 'lang-switch lang-switch--desktop';
    box.innerHTML =
      '<button type="button" class="lang-toggle" aria-haspopup="listbox" aria-expanded="false" '+
        'aria-label="Dil seçimi / Select language">'+
        '<span class="lang-code">'+CODE[active]+'</span>'+
        '<svg class="lang-caret" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2.2" aria-hidden="true"><path d="M6 9l6 6 6-6"/></svg>'+
      '</button>'+
      '<ul class="lang-menu" role="listbox" aria-label="Diller">'+optionList(active)+'</ul>';
    var ham = wrap.querySelector('.hamburger');
    wrap.insertBefore(box, ham || null);
  }
  function buildMobile(active){
    var menu = document.querySelector('.nav-menu'); if (!menu) return;
    if (menu.querySelector('.nav-lang')) return;
    var li = document.createElement('li');
    li.className = 'nav-lang';
    li.innerHTML =
      '<span class="nav-lang-label">Dil / Language</span>'+
      '<div class="nav-lang-opts" role="group" aria-label="Diller">'+
        ['tr','en','de','ar','ru'].map(function(l){
          return '<button type="button" data-lang="'+l+'" class="'+(l===active?'on':'')+'">'+CODE[l]+'</button>';
        }).join('')+
      '</div>';
    menu.appendChild(li);
  }

  function syncSwitchers(active){
    var code = document.querySelector('.lang-switch .lang-code');
    if (code) code.textContent = CODE[active];
    var opts = document.querySelectorAll('.lang-menu [data-lang]');
    opts.forEach(function(b){
      var on = b.getAttribute('data-lang')===active;
      b.classList.toggle('on', on); b.setAttribute('aria-selected', on?'true':'false');
    });
    document.querySelectorAll('.nav-lang-opts [data-lang]').forEach(function(b){
      b.classList.toggle('on', b.getAttribute('data-lang')===active);
    });
  }

  function closeAll(){
    document.querySelectorAll('.lang-switch.open').forEach(function(s){ s.classList.remove('open'); });
    var t = document.querySelector('.lang-toggle'); if (t) t.setAttribute('aria-expanded','false');
  }

  function wireSwitchers(){
    document.addEventListener('click', function(e){
      var btn = e.target.closest && e.target.closest('[data-lang]');
      if (btn){ e.preventDefault(); setLang(btn.getAttribute('data-lang')); return; }
      var tog = e.target.closest && e.target.closest('.lang-toggle');
      if (tog){
        var sw = tog.closest('.lang-switch');
        var open = sw.classList.toggle('open');
        tog.setAttribute('aria-expanded', open?'true':'false');
        return;
      }
      closeAll();
    });
    document.addEventListener('keydown', function(e){ if (e.key==='Escape') closeAll(); });
  }

  /* ---- init ---- */
  function init(){
    var lang = getLang();
    if (isAuto(lang)){
      applyDict('tr');
      document.documentElement.lang = lang;
      document.documentElement.dir = RTL.indexOf(lang)!==-1 ? 'rtl' : 'ltr';
      ensureGT();
    } else {
      clearGT();
      applyDict(lang);
    }
    buildDesktop(lang); buildMobile(lang); wireSwitchers();
  }
  if (document.readyState === 'loading') document.addEventListener('DOMContentLoaded', init);
  else init();
})();
